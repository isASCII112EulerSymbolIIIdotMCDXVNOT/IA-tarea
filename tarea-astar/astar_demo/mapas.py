"""Mapas de ejemplo. Leyenda: '#' obstáculo, 'S' inicio, 'G' meta, '.' libre."""
from __future__ import annotations

import random

from .algoritmos import Celda, Cuadricula, bfs

# Mapa 'demo': obstáculos dispersos; A* casi va en línea recta hacia la meta.
MAPA_DEMO = """\
....................
.S..................
....................
....................
......###...........
......#.............
......#....#........
...........#........
...........#...###..
..####.....#...#....
..........##...#....
................#...
....####........#...
................#...
....................
......#####.........
....................
.............#...G..
....................
....................
"""

# Mapa 'trampa': una "copa" abierta hacia el inicio. La heurística empuja a A*
# hacia el fondo de la copa y ahí se ve su límite: hay que rodearla.
MAPA_TRAMPA = """\
....................
....................
....................
....................
....................
.......######.......
............#.......
............#.......
............#.......
..S.........#....G..
............#.......
............#.......
............#.......
............#.......
.......######.......
....................
....................
....................
....................
....................
"""

MAPAS = {"demo": MAPA_DEMO, "trampa": MAPA_TRAMPA}


def cargar_mapa(texto: str) -> tuple[Cuadricula, Celda, Celda]:
    """Convierte el texto de un mapa en (cuadrícula, inicio, meta)."""
    lineas = [l for l in texto.splitlines() if l.strip()]
    ancho = len(lineas[0])
    if any(len(l) != ancho for l in lineas):
        raise ValueError("Todas las filas del mapa deben tener el mismo largo")
    grid: Cuadricula = []
    inicio = meta = None
    for f, linea in enumerate(lineas):
        fila = []
        for c, ch in enumerate(linea):
            if ch == "#":
                fila.append(1)
            else:
                fila.append(0)
                if ch == "S":
                    inicio = (f, c)
                elif ch == "G":
                    meta = (f, c)
        grid.append(fila)
    if inicio is None or meta is None:
        raise ValueError("El mapa necesita una 'S' (inicio) y una 'G' (meta)")
    return grid, inicio, meta


def generar_aleatorio(
    filas: int = 20, columnas: int = 20, densidad: float = 0.25, semilla: int = 7
) -> tuple[Cuadricula, Celda, Celda]:
    """Mapa aleatorio con solución garantizada (reintenta hasta que exista camino)."""
    rng = random.Random(semilla)
    inicio, meta = (1, 1), (filas - 2, columnas - 2)
    while True:
        grid = [[1 if rng.random() < densidad else 0 for _ in range(columnas)] for _ in range(filas)]
        grid[inicio[0]][inicio[1]] = 0
        grid[meta[0]][meta[1]] = 0
        if bfs(grid, inicio, meta).camino:
            return grid, inicio, meta


def obtener_mapa(nombre: str, semilla: int = 7) -> tuple[Cuadricula, Celda, Celda]:
    if nombre == "aleatorio":
        return generar_aleatorio(semilla=semilla)
    return cargar_mapa(MAPAS[nombre])
